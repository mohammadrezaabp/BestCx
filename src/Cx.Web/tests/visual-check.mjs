import { chromium } from '@playwright/test';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1080 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto('http://127.0.0.1:5173');
await page.waitForLoadState('networkidle');
await page.screenshot({ path: 'tests/overview-desktop.png', fullPage: true });
console.log(JSON.stringify({ errors, title: await page.title(), overflow: await page.evaluate(() => document.documentElement.scrollWidth > innerWidth) }));
await page.goto('http://127.0.0.1:5173/inbox');
await page.waitForLoadState('networkidle');
await page.screenshot({ path: 'tests/inbox-desktop.png', fullPage: true });
console.log(JSON.stringify({ errors, inbox: (await page.locator('main').innerText()).slice(0,1500) }));
await page.setViewportSize({ width: 390, height: 844 });
await page.goto('http://127.0.0.1:5173');
await page.waitForLoadState('networkidle');
await page.screenshot({ path: 'tests/overview-mobile.png', fullPage: true });
console.log(JSON.stringify({ mobileOverflow: await page.evaluate(() => document.documentElement.scrollWidth > innerWidth) }));
await browser.close();
